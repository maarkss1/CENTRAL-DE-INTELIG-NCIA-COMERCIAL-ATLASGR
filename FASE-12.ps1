function Get-DirectoryTree {
    param([Parameter(Mandatory = $true)][string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { return '' }
    $items = Get-ChildItem -LiteralPath $Path -Recurse | Sort-Object FullName
    $lines = New-Object System.Collections.Generic.List[string]
    foreach ($item in $items) {
        $lines.Add($item.FullName.Substring($Path.Length).TrimStart('\'))
    }
    $lines -join "`n"
}

function Test-GeneratedFiles {
    param([Parameter(Mandatory = $true)][string]$TargetRoot)
    $apiRoot = Join-Path $TargetRoot 'src/api'
    if (-not (Test-Path -LiteralPath $apiRoot)) {
        $Script:ValidationFindings.Add('API root not found.')
        return
    }
    $files = Get-ChildItem -LiteralPath $apiRoot -Recurse -File
    $nameMap = @{}
    foreach ($file in $files) {
        if ($file.Length -le 0) {
            $Script:ValidationFindings.Add("Empty file: $($file.FullName)")
        }
        $content = [System.IO.File]::ReadAllText($file.FullName)
        if ($content -notmatch 'export ') {
            $Script:ValidationFindings.Add("Export not found: $($file.FullName)")
        }
        if ($content -match 'TODO|FIXME|placeholder|any\b') {
            $Script:ValidationFindings.Add("Forbidden token found: $($file.FullName)")
        }
        $lower = $file.Name.ToLowerInvariant()
        if ($nameMap.ContainsKey($lower)) {
            $Script:ValidationFindings.Add("Duplicate file name detected: $($file.Name)")
        } else {
            $nameMap[$lower] = $true
        }
        $hash = Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256
        $Script:Hashes[$file.FullName] = $hash.Hash
    }
}

function Invoke-ExternalValidation {
    param([Parameter(Mandatory = $true)][string]$TargetRoot)
    $commands = @(
        @{ Name = 'npm run lint';        Command = 'npm run lint' },
        @{ Name = 'npx tsc --noEmit';    Command = 'npx tsc --noEmit' },
        @{ Name = 'npm test';           Command = 'npm test' }
    )
    $results = New-Object System.Collections.Generic.List[object]
    foreach ($item in $commands) {
        $start = Get-Date
        try {
            Push-Location $TargetRoot
            $output = & cmd /c $item.Command 2>&1
            $code = $LASTEXITCODE
            Pop-Location
        } catch {
            if ((Get-Location).Path -ne $PWD.Path) { Pop-Location }
            $output = $_.Exception.Message
            $code = 1
        }
        $elapsed = ((Get-Date) - $start).TotalSeconds
        $results.Add([pscustomobject]@{
            Name            = $item.Name
            ExitCode        = $code
            DurationSeconds = [Math]::Round($elapsed, 2)
            Output          = [string]::Join("`n", $output)
        })
    }
    $results
}

function Write-Manifest {
    param(
        [Parameter(Mandatory = $true)][string]$TargetRoot,
        [Parameter(Mandatory = $true)][AllowEmptyCollection()][object[]]$ToolResults
    )
    $duration = ((Get-Date) - $Script:StartedAt).TotalSeconds
    $manifestPath = Join-Path $TargetRoot 'phase-12-manifest.json'
    $payload = [ordered]@{
        fase              = $Script:PhaseCode
        versao            = $Script:Version
        timestamp         = (Get-Date).ToString('o')
        duracaoSegundos   = [Math]::Round($duration, 2)
        arquivosCriados   = @($Script:CreatedFiles)
        arquivosAtualizados = @($Script:UpdatedFiles)
        diretoriosCriados = @($Script:CreatedDirectories)
        hashes            = $Script:Hashes
        estatisticas      = [ordered]@{
            totalArquivosCriados     = $Script:CreatedFiles.Count
            totalArquivosAtualizados = $Script:UpdatedFiles.Count
            totalDiretoriosCriados   = $Script:CreatedDirectories.Count
            totalValidacoes          = $Script:ValidationFindings.Count
        }
        ferramentas       = $ToolResults
    }
    $json = $payload | ConvertTo-Json -Depth 10
    Write-FileFromContent -Path $manifestPath -Content $json
    $Script:ManifestFile = $manifestPath
}

