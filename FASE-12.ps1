    Write-Host ''
}

function Write-Log {
    param(
        [Parameter(Mandatory = $true)][string]$Level,
        [Parameter(Mandatory = $true)][string]$Message
    )
    $timestamp = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss')
    $line = "[$timestamp] [$Level] $Message"
    switch ($Level) {
        'ERROR' { Write-Host $line -ForegroundColor Red }
        'WARN'  { Write-Host $line -ForegroundColor Yellow }
        'OK'    { Write-Host $line -ForegroundColor Green }
        default { Write-Host $line }
    }
}

function Resolve-AbsolutePath {
    param([Parameter(Mandatory = $true)][string]$BasePath)
    $resolved = Resolve-Path -LiteralPath $BasePath -ErrorAction SilentlyContinue
    if ($null -ne $resolved) { return $resolved.Path }
    return [System.IO.Path]::GetFullPath($BasePath)
}

function Write-Folder {
    param([Parameter(Mandatory = $true)][string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) {
        if ($PSCmdlet.ShouldProcess($Path, 'Create directory')) {
            New-Item -ItemType Directory -Path $Path -Force | Out-Null
        }
        $Script:CreatedDirectories.Add($Path)
        Write-Log -Level 'OK' -Message ("Directory ready: {0}" -f $Path)
    }
}

function Write-FileFromContent {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][string]$Content
    )

    $directory = Split-Path -Parent $Path
    if (-not [string]::IsNullOrWhiteSpace($directory)) {
        Write-Folder -Path $directory
    }

    $exists = Test-Path -LiteralPath $Path
    $write = $true
    if ($exists) {
        $previous = [System.IO.File]::ReadAllText($Path)
        if ($previous -eq $Content) {
            $write = $false
        }
    }

    if ($write) {
        if ($PSCmdlet.ShouldProcess($Path, 'Write file')) {
            [System.IO.File]::WriteAllText($Path, $Content, (New-Object System.Text.UTF8Encoding($false)))
        }
        if ($exists) { $Script:UpdatedFiles.Add($Path) } else { $Script:CreatedFiles.Add($Path) }
        Write-Log -Level 'OK' -Message ("File written: {0}" -f $Path)
    }
}

