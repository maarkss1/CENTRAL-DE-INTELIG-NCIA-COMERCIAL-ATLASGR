function Invoke-Rollback {
    param([Parameter(Mandatory = $true)][string]$TargetRoot)
    $manifestPath = Join-Path $TargetRoot 'phase-12-manifest.json'
    if (-not (Test-Path -LiteralPath $manifestPath)) {
        Write-Log -Level 'ERROR' -Message 'Manifest not found for rollback.'
        return
    }
    $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
    foreach ($file in $manifest.arquivosCriados) {
        if (Test-Path -LiteralPath $file) {
            if ($PSCmdlet.ShouldProcess($file, 'Delete generated file')) {
                Remove-Item -LiteralPath $file -Force
            }
            Write-Log -Level 'OK' -Message ("Removed file: {0}" -f $file)
        }
    }
    foreach ($directory in ($manifest.diretoriosCriados | Sort-Object Length -Descending)) {
        if (Test-Path -LiteralPath $directory) {
            $children = Get-ChildItem -LiteralPath $directory -Force
            if ($children.Count -eq 0) {
                if ($PSCmdlet.ShouldProcess($directory, 'Delete empty directory')) {
                    Remove-Item -LiteralPath $directory -Force
                }
                Write-Log -Level 'OK' -Message ("Removed directory: {0}" -f $directory)
            }
        }
    }
}

