function New-TsFileContent {
    param(
        [Parameter(Mandatory = $true)][string]$Namespace,
        [Parameter(Mandatory = $true)][string]$ClassName,
        [Parameter(Mandatory = $true)][string]$Kind
    )
$header = Get-EnterpriseTsHeader
@"
$header
export interface ${ClassName}Payload {
    readonly id: string;
    readonly name: string;
    readonly timestamp: string;
    readonly metadata: Readonly<Record<string, string>>;
}

/**
 * ${ClassName}
 * Enterprise ${Kind} implementation for ${Namespace}.
 */
export class ${ClassName} {
    public readonly kind: string;
    public readonly namespace: string;

    public constructor() {
        this.kind = '${Kind}';
        this.namespace = '${Namespace}';
    }

    public describe(): string {
        return `${ClassName}::${Kind}::${Namespace}`;
    }

    public execute(payload: ${ClassName}Payload): Readonly<${ClassName}Payload> {
        return {
            id: payload.id,
            name: payload.name,
            timestamp: payload.timestamp,
            metadata: payload.metadata
        };
    }
}
"@
}

function New-IndexContent {
    param([Parameter(Mandatory = $true)][string[]]$Exports)
    $lines = @((Get-EnterpriseTsHeader).TrimEnd())
    foreach ($item in $Exports) {
        $lines += "export * from './$item';"
    }
    ($lines -join "`r`n") + "`r`n"
}

